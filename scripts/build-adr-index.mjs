#!/usr/bin/env node
// Builds docs/adr/README.md from the H1 and Status lines of docs/adr/NNNN-*.md.
// See issue #343 / ADR 0080: the index was hand-maintained and drifted (missing
// lines, hand-shortened titles) because nothing enforced it matched the files.
//
// Usage: node scripts/build-adr-index.mjs [--check [--out-root <dir>]]
// The pre-commit hook uses --staged (ADR 0349 決定1).

import { execFileSync } from 'node:child_process';
import { existsSync, lstatSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const ADR_DIR = join(ROOT, 'docs/adr');
const outRootArg = process.argv.includes('--check') ? process.argv.indexOf('--out-root') : -1;
const OUT_ROOT = outRootArg === -1 ? ROOT : process.argv[outRootArg + 1];

// The Status block is the run of paragraphs directly after the H1 (past the
// blank separator line) whose lines open with **Status ...**. Mentioning
// "Status" elsewhere — unbolded, mid-paragraph prose (e.g. ADR 0028) — is not
// a Status block and doesn't count.
function statusMarker(lines) {
  const parts = [];
  let i = 2;
  while (i < lines.length) {
    const match = lines[i].match(/^\*\*Status(?:\s*追記)?:\s*([\s\S]*?)\*\*/);
    if (!match) break;
    parts.push(match[1]);
    i++;
    while (i < lines.length && lines[i] !== '') i++;
    i++;
  }
  return parts.length ? ` **(${parts.join(' / ')})**` : '';
}

function render(files, read) {
  // Duplicate ADR numbers make citation addresses ambiguous (issue #1148).
  const duplicates = files.map((f) => f.slice(0, 4)).filter((num, i, nums) => nums.indexOf(num) !== i);
  if (duplicates.length) {
    throw new Error(`duplicate ADR number(s): ${[...new Set(duplicates)].join(', ')} — renumber the later one`);
  }
  const entries = files.map((file) => {
    const num = file.slice(0, 4);
    const lines = read(file).split('\n');
    const h1 = lines[0].replace(/^#\s*/, '');
    return `- [${num}](${file}) — ${h1}${statusMarker(lines)}`;
  });
  const header =
    '# ADR Index\n\n' +
    "Generated by `node scripts/build-adr-index.mjs` — do not edit directly. One line per ADR, " +
    "in file order; each line is the ADR's H1 title. When an ADR is superseded, the marker at " +
    'the end of its line captures its Status update(s).\n\n';
  return header + entries.join('\n') + '\n';
}

function git(args, input) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', input });
}

function staged() {
  const changed = git(['diff', '--cached', '--name-only', '--no-renames', '-z', '--', 'docs/adr']).split('\0');
  if (!changed.some((path) => /^docs\/adr\/\d{4}-.*\.md$/.test(path))) return;
  const files = git(['ls-files', '-z', '--', 'docs/adr']).split('\0')
    .filter((path) => /^docs\/adr\/\d{4}-.*\.md$/.test(path)).sort();
  const out = render(files.map((path) => path.slice('docs/adr/'.length)),
    (file) => git(['show', `:docs/adr/${file}`]));
  const readme = 'docs/adr/README.md';
  const outputPath = join(ROOT, readme);
  const tracked = git(['ls-files', '-z', '--', readme]) !== '';
  const current = tracked ? git(['show', `:${readme}`]) : undefined;
  const stat = lstatSync(outputPath, { throwIfNoEntry: false });
  const present = stat !== undefined;
  if ((present && !stat.isFile()) ||
      (tracked ? !present || readFileSync(outputPath, 'utf8') !== current : present)) {
    throw new Error(`${readme} has unstaged or untracked changes; stage or save them before committing`);
  }
  if (current === out) return;
  // ADR 0349 決定1: --only uses next-index-<pid>.lock; adding README there leaves the normal index stale.
  const index = process.env.GIT_INDEX_FILE;
  if (index && /^next-index-\d+\.lock$/.test(basename(index)) &&
      dirname(resolve(ROOT, index)) === git(['rev-parse', '--absolute-git-dir']).trim()) {
    throw new Error('path-limited commit needs an ADR index update; use git add, then git commit without paths');
  }
  const previous = present ? readFileSync(outputPath) : undefined;
  // Stage the validated bytes directly: git add could run a clean filter on the generated index.
  const oid = git(['hash-object', '-w', '--stdin'], out).trim();
  writeFileSync(outputPath, out);
  try {
    git(['update-index', '--add', '--cacheinfo', `100644,${oid},${readme}`]);
  } catch (error) {
    if (previous) writeFileSync(outputPath, previous);
    else unlinkSync(outputPath);
    throw error;
  }
}

try {
  if (process.argv.includes('--staged')) {
    staged();
  } else {
    const files = readdirSync(ADR_DIR).filter((name) => /^\d{4}-.*\.md$/.test(name)).sort();
    const out = render(files, (file) => readFileSync(join(ADR_DIR, file), 'utf8'));
    const outputPath = join(OUT_ROOT, 'docs/adr/README.md');
    if (process.argv.includes('--check')) {
      if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== out) {
        throw new Error('stale generated asset: docs/adr/README.md');
      }
      console.log('docs/adr/README.md is fresh');
    } else {
      writeFileSync(outputPath, out);
      console.log(`built docs/adr/README.md from ${files.length} ADRs`);
    }
  }
} catch (error) {
  console.error(`ADR index: ${error.message}`);
  process.exitCode = 1;
}
