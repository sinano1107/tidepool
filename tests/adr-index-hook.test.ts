import { spawnSync } from "node:child_process";
import { chmodSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { describe, expect, it } from "vitest";
import { tempDir } from "./temp-dir.js";

const ROOT = join(import.meta.dirname, "..");
const README = "docs/adr/README.md";
const ADR = "docs/adr/0001-first.md";
const HEADER = "# ADR Index\n\nGenerated by `node scripts/build-adr-index.mjs` — do not edit directly. One line per ADR, in file order; each line is the ADR's H1 title. When an ADR is superseded, the marker at the end of its line captures its Status update(s).\n\n";
const INITIAL = `${HEADER}- [0001](0001-first.md) — First\n`;

function run(cwd: string, command: string, args: string[], env: NodeJS.ProcessEnv = {}) {
  return spawnSync(command, args, {
    cwd, encoding: "utf8",
    env: { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_CONFIG_NOSYSTEM: "1", ...env },
  });
}
function git(cwd: string, ...args: string[]) {
  const result = run(cwd, "git", args);
  if (result.status !== 0) throw new Error(`${args.join(" ")}: ${result.stderr}`);
  return result.stdout;
}
function put(cwd: string, path: string, contents: string) {
  mkdirSync(dirname(join(cwd, path)), { recursive: true });
  writeFileSync(join(cwd, path), contents);
}
async function fixture() {
  const repo = await tempDir("adr-hook-");
  cpSync(join(ROOT, "scripts"), join(repo, "scripts"), { recursive: true });
  if (existsSync(join(ROOT, ".githooks"))) cpSync(join(ROOT, ".githooks"), join(repo, ".githooks"), { recursive: true });
  git(repo, "init", "-q");
  git(repo, "config", "user.name", "ADR test");
  git(repo, "config", "user.email", "adr@example.test");
  put(repo, ADR, "# First\n\nOriginal body\n");
  put(repo, README, INITIAL);
  put(repo, "other.txt", "original\n");
  git(repo, "add", ".");
  git(repo, "-c", "core.hooksPath=/dev/null", "commit", "-qm", "initial");
  git(repo, "config", "core.hooksPath", ".githooks");
  return repo;
}

describe("ADR index pre-commit", () => {
  it("commits the index generated from staged ADRs and preserves unstaged content", async () => {
    const repo = await fixture();
    put(repo, ADR, "# Staged title\n\n**Status: superseded**\n\n**Status 追記: follow-up**\n\nBody\n");
    git(repo, "add", ADR);
    const unstaged = "# Unstaged title\n\nBody edited after staging\n";
    put(repo, ADR, unstaged);
    put(repo, "docs/adr/0002-untracked.md", "# Untracked\n");
    put(repo, "other.txt", "staged other\n");
    git(repo, "add", "other.txt");
    put(repo, "other.txt", "unstaged other\n");
    git(repo, "commit", "-qm", "ADR change");
    const expected = `${HEADER}- [0001](0001-first.md) — Staged title **(superseded / follow-up)**\n`;
    expect(git(repo, "show", `HEAD:${README}`)).toBe(expected);
    expect(readFileSync(join(repo, README), "utf8")).toBe(expected);
    expect(readFileSync(join(repo, ADR), "utf8")).toBe(unstaged);
    expect(git(repo, "show", "HEAD:other.txt")).toBe("staged other\n");
    expect(readFileSync(join(repo, "other.txt"), "utf8")).toBe("unstaged other\n");
    expect(git(repo, "diff", "--cached", "--name-only")).toBe("");
  }, 30_000);
  it.each(["edited", "deleted", "untracked"])("refuses an %s README without changing either index or the worktree", async (state) => {
    const repo = await fixture();
    put(repo, ADR, "# Changed\n");
    git(repo, "add", ADR);
    if (state === "deleted") rmSync(join(repo, README));
    else put(repo, README, "Hand-written README\n");
    if (state === "untracked") git(repo, "rm", "--cached", README);
    const before = git(repo, "ls-files", "--stage");
    const result = run(repo, "git", ["commit", "-qm", "must abort"]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain(README);
    expect(git(repo, "ls-files", "--stage")).toBe(before);
    expect(existsSync(join(repo, README))).toBe(state !== "deleted");
    if (state !== "deleted") expect(readFileSync(join(repo, README), "utf8")).toBe("Hand-written README\n");
    expect(git(repo, "log", "--format=%s", "-1")).toBe("initial\n");
  }, 30_000);

  it("rejects a path-limited commit before README mutation and allows a staged retry", async () => {
    const repo = await fixture();
    put(repo, ADR, "# Staged title\n");
    git(repo, "add", ADR);
    put(repo, ADR, "# Path commit title\n");
    put(repo, "other.txt", "staged other\n");
    git(repo, "add", "other.txt");
    const staged = git(repo, "ls-files", "--stage");
    put(repo, ".githooks/pre-commit", "#!/bin/sh\ngit ls-files --stage > .git/active-before\nnode scripts/build-adr-index.mjs --staged\nresult=$?\ngit ls-files --stage > .git/active-after\nexit \"$result\"\n");
    const result = run(repo, "git", ["commit", "-qm", "limited", "--", ADR]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain("path-limited");
    expect(readFileSync(join(repo, ".git/active-after"))).toEqual(readFileSync(join(repo, ".git/active-before")));
    expect(result.stderr).toContain("git add");
    expect(readFileSync(join(repo, README), "utf8")).toBe(INITIAL);
    expect(git(repo, "ls-files", "--stage")).toBe(staged);
    expect(readFileSync(join(repo, ADR), "utf8")).toBe("# Path commit title\n");
    git(repo, "add", ADR);
    git(repo, "commit", "-qm", "ordinary retry");
    expect(git(repo, "show", `HEAD:${README}`)).toBe(`${HEADER}- [0001](0001-first.md) — Path commit title\n`);
    expect(git(repo, "diff", "--cached", "--name-only")).toBe("");
  }, 30_000);

  it("commit -a includes its ADR snapshot and leaves no reverse README staging", async () => {
    const repo = await fixture();
    put(repo, ADR, "# Included by -a\n");
    git(repo, "commit", "-aqm", "all tracked edits");
    expect(git(repo, "show", `HEAD:${README}`)).toBe(`${HEADER}- [0001](0001-first.md) — Included by -a\n`);
    expect(git(repo, "status", "--porcelain")).toBe("");
  }, 30_000);

  it("regenerates for additions, renames, and deletions from the whole staged ADR set", async () => {
    const repo = await fixture();
    put(repo, "docs/adr/0002-second.md", "# Second\n");
    git(repo, "add", "docs/adr/0002-second.md");
    git(repo, "commit", "-qm", "add ADR");
    expect(git(repo, "show", `HEAD:${README}`)).toBe(`${INITIAL}- [0002](0002-second.md) — Second\n`);
    git(repo, "mv", ADR, "docs/adr/0001-renamed.md");
    git(repo, "rm", "docs/adr/0002-second.md");
    git(repo, "commit", "-qm", "rename and delete");
    expect(git(repo, "show", `HEAD:${README}`)).toBe(`${HEADER}- [0001](0001-renamed.md) — First\n`);
  }, 30_000);

  it("uses the linked worktree's checkout, staged content, and index", async () => {
    const repo = await fixture();
    const linked = join(await tempDir("adr-linked-"), "checkout");
    git(repo, "worktree", "add", "-qb", "linked", linked);
    put(linked, ADR, "# Linked staged\n");
    git(linked, "add", ADR);
    put(linked, ADR, "# Linked unstaged\n");
    put(repo, ADR, "# Main unstaged\n");
    git(linked, "commit", "-qm", "linked ADR");
    expect(git(linked, "show", `HEAD:${README}`)).toBe(`${HEADER}- [0001](0001-first.md) — Linked staged\n`);
    expect(readFileSync(join(linked, ADR), "utf8")).toBe("# Linked unstaged\n");
    expect(readFileSync(join(repo, README), "utf8")).toBe(INITIAL);
    expect(readFileSync(join(repo, ADR), "utf8")).toBe("# Main unstaged\n");
    expect(git(repo, "show", `HEAD:${README}`)).toBe(INITIAL);
  }, 30_000);

  it("honors an explicit GIT_INDEX_FILE without staging into the default index", async () => {
    const repo = await fixture();
    const index = join(repo, ".git/custom-index");
    cpSync(join(repo, ".git/index"), index);
    put(repo, ADR, "# Alternate index\n");
    expect(run(repo, "git", ["add", ADR], { GIT_INDEX_FILE: index }).status).toBe(0);
    const defaultBefore = git(repo, "ls-files", "--stage");
    const result = run(repo, "git", ["commit", "-qm", "custom index"], { GIT_INDEX_FILE: index });
    expect(result.stderr).toBe("");
    expect(result.status).toBe(0);
    expect(git(repo, "show", `HEAD:${README}`)).toBe(`${HEADER}- [0001](0001-first.md) — Alternate index\n`);
    expect(git(repo, "ls-files", "--stage")).toBe(defaultBefore);
    expect(run(repo, "git", ["diff", "--cached", "--name-only"], { GIT_INDEX_FILE: index }).stdout).toBe("");
  }, 30_000);

  it("refuses a dangling README symlink without writing its target", async () => {
    const repo = await fixture();
    put(repo, ADR, "# Changed\n");
    git(repo, "add", ADR);
    rmSync(join(repo, README));
    symlinkSync("../../unexpected-output", join(repo, README));
    git(repo, "rm", "--cached", README);
    const staged = git(repo, "ls-files", "--stage");
    const result = run(repo, "git", ["commit", "-qm", "must abort"]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain(README);
    expect(existsSync(join(repo, "unexpected-output"))).toBe(false);
    expect(git(repo, "ls-files", "--stage")).toBe(staged);
  }, 30_000);

  it("stages the generated bytes even when README has a Git clean filter", async () => {
    const repo = await fixture();
    put(repo, ".gitattributes", "docs/adr/README.md filter=corrupt\n");
    git(repo, "config", "filter.corrupt.clean", "printf altered");
    put(repo, ADR, "# Exact generated bytes\n");
    git(repo, "add", ADR);
    git(repo, "commit", "-qm", "ADR with attributes");
    const expected = `${HEADER}- [0001](0001-first.md) — Exact generated bytes\n`;
    expect(git(repo, "show", `HEAD:${README}`)).toBe(expected);
    expect(readFileSync(join(repo, README), "utf8")).toBe(expected);
  }, 30_000);

  it("leaves README alone when the commit has no ADR changes", async () => {
    const repo = await fixture();
    put(repo, README, "unstaged README\n");
    put(repo, ADR, "# Unstaged ADR\n");
    put(repo, "other.txt", "commit this\n");
    git(repo, "add", "other.txt");
    git(repo, "commit", "-qm", "unrelated");
    expect(readFileSync(join(repo, README), "utf8")).toBe("unstaged README\n");
    expect(git(repo, "show", `HEAD:${README}`)).toBe(INITIAL);
    expect(git(repo, "diff", "--cached", "--name-only")).toBe("");
  }, 30_000);

  it("rejects duplicate ADR numbers in manual, check, and staged generation before changing README", async () => {
    const repo = await fixture();
    put(repo, "docs/adr/0001-duplicate.md", "# Duplicate\n");
    for (const args of [[], ["--check"]]) {
      const result = run(repo, process.execPath, ["scripts/build-adr-index.mjs", ...args]);
      expect(result.status).toBe(1);
      expect(result.stderr).toContain("duplicate ADR number(s): 0001");
      expect(readFileSync(join(repo, README), "utf8")).toBe(INITIAL);
    }
    git(repo, "add", "docs/adr/0001-duplicate.md");
    const staged = git(repo, "ls-files", "--stage");
    const result = run(repo, "git", ["commit", "-qm", "duplicate"]);
    expect(result.status).not.toBe(0);
    expect(result.stderr).toContain("duplicate ADR number(s): 0001");
    expect(readFileSync(join(repo, README), "utf8")).toBe(INITIAL);
    expect(git(repo, "ls-files", "--stage")).toBe(staged);
  }, 30_000);

  it.each(["Node", "Git"])("fails clearly when %s is unavailable", async (missing) => {
    const repo = await fixture();
    put(repo, ADR, "# Changed\n");
    git(repo, "add", ADR);
    const gitPath = run(repo, "/bin/sh", ["-c", "command -v git"]).stdout.trim();
    const bin = join(repo, "bin");
    mkdirSync(bin);
    if (missing === "Git") symlinkSync(process.execPath, join(bin, "node"));
    const staged = git(repo, "ls-files", "--stage");
    const result = missing === "Node"
      ? run(repo, gitPath, ["commit", "-qm", "missing runtime"], { PATH: bin })
      : run(repo, process.execPath, ["scripts/build-adr-index.mjs", "--staged"], { PATH: bin });
    expect(result.status).not.toBe(0);
    expect(result.stderr.toLowerCase()).toContain(missing.toLowerCase());
    expect(readFileSync(join(repo, README), "utf8")).toBe(INITIAL);
    expect(git(repo, "ls-files", "--stage")).toBe(staged);
  }, 30_000);

});


describe("ADR hook installer", () => {
  function install(repo: string, env: NodeJS.ProcessEnv = {}) {
    return run(repo, process.execPath, ["scripts/install-git-hooks.mjs"], env);
  }

  it("sets the relative hooksPath once and does not rewrite an existing setting", async () => {
    const repo = await fixture();
    git(repo, "config", "--unset", "core.hooksPath");
    const first = install(repo);
    expect(first.stderr).toBe("");
    expect(first.status).toBe(0);
    expect(git(repo, "config", "--get", "core.hooksPath")).toBe(".githooks\n");
    const config = readFileSync(join(repo, ".git/config"));
    put(repo, ".git/config.lock", "held lock");
    const second = install(repo);
    expect(second.status).toBe(0);
    expect(second.stdout).toContain("already");
    expect(readFileSync(join(repo, ".git/config"))).toEqual(config);
  }, 30_000);
  it("keeps an existing hooksPath and explains the skip", async () => {
    const repo = await fixture();
    git(repo, "config", "core.hooksPath", "somewhere-else");
    const config = readFileSync(join(repo, ".git/config"));
    const result = install(repo);
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("skipped");
    expect(result.stdout).toContain("somewhere-else");
    expect(readFileSync(join(repo, ".git/config"))).toEqual(config);
  }, 30_000);

  it("does not configure a non-checkout package inside an unrelated parent repo", async () => {
    const repo = await fixture();
    const nested = join(repo, "nested-package");
    cpSync(join(repo, "scripts"), join(nested, "scripts"), { recursive: true });
    const config = readFileSync(join(repo, ".git/config"));
    const result = install(nested);
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("skipped");
    expect(result.stdout).toContain("checkout");
    expect(readFileSync(join(repo, ".git/config"))).toEqual(config);
  }, 30_000);

  it("preserves active default hooks instead of disabling them", async () => {
    const repo = await fixture();
    git(repo, "config", "--unset", "core.hooksPath");
    put(repo, ".git/hooks/pre-push", "#!/bin/sh\nexit 0\n");
    chmodSync(join(repo, ".git/hooks/pre-push"), 0o755);
    const config = readFileSync(join(repo, ".git/config"));
    const result = install(repo);
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("skipped");
    expect(result.stdout).toContain("pre-push");
    expect(readFileSync(join(repo, ".git/config"))).toEqual(config);
  }, 30_000);

  it("npm install and ci run prepare and keep installation successful when config is locked", async () => {
    const repo = await fixture();
    git(repo, "config", "--unset", "core.hooksPath");
    const packageJson = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
    put(repo, "package.json", JSON.stringify({ name: "adr-hook-test", version: "1.0.0", scripts: { prepare: packageJson.scripts.prepare } }));
    const npmEnv = { npm_config_cache: join(repo, ".npm-cache"), NPM_CONFIG_USERCONFIG: join(repo, ".npmrc-user"), NPM_CONFIG_GLOBALCONFIG: join(repo, ".npmrc-global") };
    const installed = run(repo, "npm", ["install", "--offline", "--no-audit", "--no-fund"], npmEnv);
    expect(installed.stderr).toBe("");
    expect(installed.status).toBe(0);
    expect(git(repo, "config", "--get", "core.hooksPath")).toBe(".githooks\n");
    git(repo, "config", "--unset", "core.hooksPath");
    put(repo, ".git/config.lock", "held lock");
    const ci = run(repo, "npm", ["ci", "--offline", "--no-audit", "--no-fund"], npmEnv);
    expect(ci.status).toBe(0);
    expect(ci.stdout).toContain("Git hooks skipped:");
    expect(run(repo, "git", ["config", "--get", "core.hooksPath"]).status).toBe(1);
  }, 30_000);

  it.each(["no Git", "not a checkout", "read-only Git directory"])("skips %s without failing installation", async (state) => {
    const repo = await fixture();
    git(repo, "config", "--unset", "core.hooksPath");
    const config = readFileSync(join(repo, ".git/config"));
    if (state === "not a checkout") rmSync(join(repo, ".git"), { recursive: true });
    if (state === "read-only Git directory") chmodSync(join(repo, ".git"), 0o555);
    try {
      const result = install(repo, state === "no Git" ? { PATH: "/nonexistent" } : {});
      expect(result.status).toBe(0);
      expect(result.stdout).toContain("skipped");
      if (state !== "not a checkout") expect(readFileSync(join(repo, ".git/config"))).toEqual(config);
    } finally {
      if (state === "read-only Git directory") chmodSync(join(repo, ".git"), 0o755);
    }
  }, 30_000);

  it("installs in a linked worktree and ignores sample or non-executable hooks", async () => {
    const repo = await fixture();
    git(repo, "config", "--unset", "core.hooksPath");
    put(repo, ".git/hooks/pre-commit", "not executable\n");
    const linked = join(await tempDir("adr-installer-linked-"), "checkout");
    git(repo, "worktree", "add", "-qb", "installer", linked);
    const result = install(linked);
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("configured");
    expect(git(linked, "config", "--get", "core.hooksPath")).toBe(".githooks\n");
  }, 30_000);

});
